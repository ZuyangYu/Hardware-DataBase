"""Versioned PostgreSQL schema for the control plane (v3 §5.2).

The execution core is pinned by hand-written DDL so the target contract never
silently follows source drift.  Tables outside the core get explicit
type-mapped DDL generated from the frozen SQLite snapshot (see ``loader``).
Foreign keys and secondary indexes are created after data load so import order
cannot fail on cycles.

Type rules (explicit, no declaration-string guessing):

- ``*_json`` columns and the registered extras become ``JSONB``;
- ``*_at`` columns become ``TIMESTAMPTZ`` (assumed UTC when the source value
  has no offset);
- the registered 0/1 columns become ``BOOLEAN``;
- single-column INTEGER primary keys become ``BIGINT GENERATED BY DEFAULT AS
  IDENTITY``;
- ID columns stay ``TEXT`` for migration fidelity: the source writes 32-hex
  turn ids and empty-string references that a UUID column would reject.  The
  UUID tightening from the plan's illustrative DDL is deliberately deferred to
  a later schema version that includes data cleanup.
"""

