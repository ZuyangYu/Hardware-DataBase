# Escape hatch for columns that must stay TEXT despite a suffix rule.
TEXT_EXTRA_COLUMNS: set[tuple[str, str]] = set()

_INTEGER_TYPES = ("INT", "BIGINT", "SMALLINT", "TINYINT")
_REAL_TYPES = ("REAL", "FLOAT", "DOUBLE", "NUMERIC", "DECIMAL")


SCHEMA_TABLE_DDL = f"""
    CREATE TABLE IF NOT EXISTS {SCHEMA_TABLE} (
        key TEXT PRIMARY KEY,
        value TEXT NOT NULL,
        updated_at TIMESTAMPTZ NOT NULL
    )
"""


def pg_ident(name: str) -> str:
    return '"' + str(name).replace('"', '""') + '"'


def is_core_table(table: str) -> bool:
    return str(table).lower() in CORE_TABLE_DDL


def apply_schema(conn, *, include_indexes: bool = False) -> None:
    """Create the version table and core tables on an autocommit connection.

    Secondary indexes are intentionally separate: the loader creates them
    after the data load so unique violations surface with the data intact.
    """
    conn.execute(SCHEMA_TABLE_DDL)
    for ddl in CORE_TABLE_DDL.values():
        conn.execute(ddl)
    if include_indexes:
        create_core_indexes(conn)


def create_core_indexes(conn) -> None:
    for ddl in CORE_INDEX_DDL:
        conn.execute(ddl)


def pg_type_for(table: str, column: str, declared: str = "") -> str:
    """Explicit SQLite→PostgreSQL type mapping (no guessing)."""
    if str(table).lower() in AUTH_DOMAIN_TABLES or str(table).lower().startswith("quality_"):
        # 认证域：机械映射（TEXT 保真），见 AUTH_DOMAIN_TABLES 注释。
        value = str(declared or "").upper()
        if "BLOB" in value:
            return "BYTEA"
        if any(token in value for token in _INTEGER_TYPES):
            return "BIGINT"
        if any(token in value for token in _REAL_TYPES):
            return "DOUBLE PRECISION"
        return "TEXT"
    key = (str(table).lower(), str(column).lower())
    if key in TEXT_EXTRA_COLUMNS:
        return "TEXT"
    if key in JSONB_EXTRA_COLUMNS or str(column).lower().endswith("_json"):
        return "JSONB"
    if key in BOOLEAN_EXTRA_COLUMNS:
        return "BOOLEAN"
    if str(column).lower().endswith("_at"):
        return "TIMESTAMPTZ"
    value = str(declared or "").upper()
    if "BOOL" in value:
        return "BOOLEAN"
    if "BLOB" in value:
        return "BYTEA"
    if any(token in value for token in _INTEGER_TYPES):
        return "BIGINT"
    if any(token in value for token in _REAL_TYPES):
        return "DOUBLE PRECISION"
    return "TEXT"


def _render_default(raw: Any, type_sql: str) -> str | None:
    """Translate a simple SQLite literal default; skip expressions.

    Only literals the loader can prove equivalent are carried over.  Anything
    with parentheses (functions/expressions) is dropped so the column keeps
    NOT NULL without a default and callers must supply the value explicitly.
    """
    text = str(raw or "").strip()
    if not text or text.upper() == "NULL" or any(ch in text for ch in "()"):
        return None
    if text.upper() in {"CURRENT_TIMESTAMP", "CURRENT_TIME", "CURRENT_DATE"}:
        return "now()" if type_sql == "TIMESTAMPTZ" else None
    if text.startswith("'") and text.endswith("'") and len(text) >= 2:
        if type_sql == "TIMESTAMPTZ":
            # SQLite text timestamps often default to '' as a sentinel; that is
            # not a valid timestamptz literal, so no default is carried over.
            return None
        if type_sql == "JSONB":
            # SQLite 把 JSON 存成 TEXT：'' 是"未设置"哨兵而非合法 JSON，
            # 非法 JSON 字面量同样不能带进 PG（否则建表即报错）。
            inner = text[1:-1].replace("''", "'")
            if not inner.strip():
                return None
            try:
                json.loads(inner)
            except ValueError:
                return None
            return f"{text}::jsonb"
        if type_sql == "BOOLEAN":
            lowered = text.strip("'").lower()
            if lowered in {"0", "false", "f", "no", ""}:
                return "FALSE"
            if lowered in {"1", "true", "t", "yes"}:
                return "TRUE"
            return None
        return text
    if type_sql == "BOOLEAN":
        if text in {"0", "1"}:
            return "TRUE" if text == "1" else "FALSE"
        return None
    if type_sql == "BIGINT":
        try:
            int(text)
        except ValueError:
            return None
        return text
    if type_sql == "DOUBLE PRECISION":
        try:
            float(text)
        except ValueError:
            return None
        return text
    return None


def generated_table_ddl(table: str, columns: list[dict[str, Any]]) -> str:
    """Build DDL for a non-core table from frozen SQLite column metadata."""
    definitions: list[str] = []
    primary_columns = [column for column in columns if int(column.get("pk") or 0) > 0]
    primary_keys = sorted((int(column["pk"]), str(column["name"])) for column in primary_columns)
    single_integer_pk = len(primary_columns) == 1 and (
        pg_type_for(
            table,
            str(primary_columns[0]["name"]),
            str(primary_columns[0].get("type") or ""),
        )
        == "BIGINT"
    )
    for column in columns:
        name = str(column["name"])
        type_sql = pg_type_for(table, name, str(column.get("type") or ""))
        parts = [pg_ident(name), type_sql]
        is_pk = int(column.get("pk") or 0) > 0
        if is_pk and single_integer_pk:
            parts.append("GENERATED BY DEFAULT AS IDENTITY")
        if int(column.get("notnull") or 0):
            parts.append("NOT NULL")
        default = _render_default(column.get("dflt_value"), type_sql)
        if default is not None:
            parts.append(f"DEFAULT {default}")
        definitions.append(" ".join(parts))
    if primary_keys:
        definitions.append(
            "PRIMARY KEY ("
            + ", ".join(pg_ident(name) for _, name in primary_keys)
            + ")"
        )
    return f"CREATE TABLE IF NOT EXISTS {pg_ident(table)} ({', '.join(definitions)})"


def generated_identity_column(
    table: str, columns: list[dict[str, Any]]
) -> tuple[str, str] | None:
    """Return the identity (table, column) for a generated single-INTEGER-PK table."""
    primary_columns = [column for column in columns if int(column.get("pk") or 0) > 0]
    if len(primary_columns) != 1:
        return None
    column = str(primary_columns[0]["name"])
    if (
        pg_type_for(table, column, str(primary_columns[0].get("type") or ""))
        == "BIGINT"
    ):
        return (table, column)
    return None
