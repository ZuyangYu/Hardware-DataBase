"""Unit tests for control-plane schema typing, DDL and value adaptation (v3 PR-2)."""

from __future__ import annotations

import unittest

from src.storage.control_plane import schema
from src.storage.control_plane.loader import adapt_value, canonical_value
from src.storage.control_plane.schema_version import assert_schema_compatible


class TypeMappingTests(unittest.TestCase):
    def test_json_suffix_and_registered_extras_become_jsonb(self):
        self.assertEqual(schema.pg_type_for("chat_turns", "summary_json", "TEXT"), "JSONB")
        self.assertEqual(
            schema.pg_type_for("chat_turns", "required_attachment_ids", "TEXT"), "JSONB"
        )
        self.assertEqual(
            schema.pg_type_for(
                "conversation_execution_state", "recoverable_checkpoint_ref", "TEXT"
            ),
            "JSONB",
        )

    def test_timestamp_boolean_integer_and_blob_rules(self):
        self.assertEqual(schema.pg_type_for("chat_turns", "created_at", "TEXT"), "TIMESTAMPTZ")
        self.assertEqual(
            schema.pg_type_for("chat_turns", "cancel_requested", "INTEGER"), "BOOLEAN"
        )
        self.assertEqual(schema.pg_type_for("chat_turns", "retry_count", "INTEGER"), "BIGINT")
        self.assertEqual(schema.pg_type_for("any", "ratio", "REAL"), "DOUBLE PRECISION")
        self.assertEqual(schema.pg_type_for("any", "blob", "BLOB"), "BYTEA")
        self.assertEqual(schema.pg_type_for("any", "title", "VARCHAR(200)"), "TEXT")

    def test_generated_ddl_translates_literal_defaults(self):
        columns = [
            {"name": "id", "type": "INTEGER", "notnull": 0, "pk": 1, "dflt_value": None},
            {"name": "retry_count", "type": "INTEGER", "notnull": 1, "pk": 0, "dflt_value": "0"},
            {"name": "status", "type": "TEXT", "notnull": 1, "pk": 0, "dflt_value": "'pending'"},
            {"name": "payload_json", "type": "TEXT", "notnull": 1, "pk": 0, "dflt_value": "'{}'"},
            {"name": "active", "type": "INTEGER", "notnull": 1, "pk": 0, "dflt_value": "1"},
            {
                "name": "stamped_at",
                "type": "TEXT",
                "notnull": 0,
                "pk": 0,
                "dflt_value": "(datetime('now'))",
            },
        ]
        ddl = schema.generated_table_ddl("sample", columns)
        self.assertIn('"retry_count" BIGINT NOT NULL DEFAULT 0', ddl)
        self.assertIn('"status" TEXT NOT NULL DEFAULT \'pending\'', ddl)
        self.assertIn('"payload_json" JSONB NOT NULL DEFAULT \'{}\'::jsonb', ddl)
        self.assertIn('"active" BIGINT NOT NULL DEFAULT 1', ddl)
        self.assertNotIn("datetime", ddl)

    def test_generated_ddl_pins_identity_and_constraints(self):
        columns = [
            {"name": "id", "type": "INTEGER", "notnull": 0, "pk": 1},
            {"name": "payload_json", "type": "TEXT", "notnull": 1, "pk": 0},
            {"name": "seen_at", "type": "TEXT", "notnull": 0, "pk": 0},
        ]
        ddl = schema.generated_table_ddl("sample", columns)
        self.assertIn('"id" BIGINT GENERATED BY DEFAULT AS IDENTITY', ddl)
        self.assertIn('"payload_json" JSONB NOT NULL', ddl)
        self.assertIn('"seen_at" TIMESTAMPTZ', ddl)
        self.assertIn('PRIMARY KEY ("id")', ddl)


class ValueAdaptationTests(unittest.TestCase):
    def test_json_adaptation_parses_and_maps_empty_to_null(self):
        adapted = adapt_value("JSONB", '{"b": 1, "a": 2}', table="t", column="c")
        self.assertEqual(adapted.obj, {"b": 1, "a": 2})
        self.assertIsNone(adapt_value("JSONB", "", table="t", column="c"))
        self.assertIsNone(adapt_value("JSONB", None, table="t", column="c"))
        with self.assertRaises(ValueError):
            adapt_value("JSONB", "{bad", table="t", column="c")

    def test_canonical_json_is_order_insensitive(self):
        left = canonical_value("JSONB", '{"b": 1, "a": 2}', table="t", column="c")
        right = canonical_value("JSONB", {"a": 2, "b": 1}, table="t", column="c")
        self.assertEqual(left, right)

    def test_naive_timestamp_is_assumed_utc(self):
        value = canonical_value("TIMESTAMPTZ", "2026-09-17 12:00:00", table="t", column="c")
        self.assertEqual(value, "2026-09-17T12:00:00.000000+00:00")
        offset = canonical_value(
            "TIMESTAMPTZ", "2026-09-17T20:00:00+08:00", table="t", column="c"
        )
        self.assertEqual(offset, "2026-09-17T12:00:00.000000+00:00")
        with self.assertRaises(ValueError):
            canonical_value("TIMESTAMPTZ", "not-a-time", table="t", column="c")

    def test_boolean_variants(self):
        for raw, expected in ((1, True), ("1", True), ("true", True), (0, False), ("false", False)):
            self.assertIs(canonical_value("BOOLEAN", raw, table="t", column="c"), expected)
        with self.assertRaises(ValueError):
            canonical_value("BOOLEAN", "maybe", table="t", column="c")


class SchemaContractTests(unittest.TestCase):
    def test_core_tables_have_pinned_ddl(self):
        for table in schema.CORE_TABLES:
            self.assertIn(table, schema.CORE_TABLE_DDL)

    def test_turn_status_contract_matches_conversation_service(self):
        from src.core.conversation import TURN_STATUSES_NON_TERMINAL

        for status in TURN_STATUSES_NON_TERMINAL:
            self.assertIn(status, schema.TURN_STATUSES)
        for status in ("completed", "failed", "cancelled"):
            self.assertIn(status, schema.TURN_STATUSES)

    def test_assert_schema_compatible_fails_closed_without_schema(self):
        class _MissingTableConnection:
            def execute(self, *args, **kwargs):
                raise RuntimeError("relation does not exist")

        with self.assertRaises(RuntimeError):
            assert_schema_compatible(_MissingTableConnection())


if __name__ == "__main__":
    unittest.main()
